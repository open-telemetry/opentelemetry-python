"""Fuzz W3C baggage handling in W3CBaggagePropagator.

List-members are generated by Hypothesis from ``fuzz/grammars/baggage.lark``,
a translation of the W3C Baggage ABNF (https://www.w3.org/TR/baggage/#definition).
"""

import logging
import re
import sys
from collections.abc import Callable
from pathlib import Path
from urllib.parse import quote, unquote

import atheris
from _strategies import Mutation, char_mutations, split_headers
from hypothesis import HealthCheck, assume, given, settings
from hypothesis import strategies as st
from hypothesis.extra.lark import from_lark
from lark import Lark, Token, UnexpectedInput

with atheris.instrument_imports():
    from opentelemetry import baggage
    from opentelemetry.baggage.propagation import W3CBaggagePropagator
    from opentelemetry.context.context import Context

_PROPAGATOR = W3CBaggagePropagator()
_GRAMMAR = Lark.open(str(Path(__file__).parent.parent / "grammars" / "baggage.lark"), parser="lalr")

_MAX_PAIRS = 180
_MAX_PAIR_LENGTH = 4096
_MAX_LENGTH = 8192

# Whitespace allowed around list members (OWS, RFC 9110 section 5.6.3)
_OWS = " \t"

# Characters that are invalid in a key, a value, or both
_INVALID_CHARS = ',;="\\ \t\x00\x1f\x7f\x80é \U0001f600'
# Percent-escapes that are incomplete, not hex, or not valid UTF-8, next to valid ones
_PERCENT_ESCAPES = ["%", "%4", "%41", "%zz", "%00", "%7F", "%C3", "%C3%A9", "%E2%80", "%FF", "%F0%9F%98%80"]
_RANDOM_ALPHABET = st.one_of(
    st.sampled_from(',=;%" \t\\'),
    st.characters(min_codepoint=0x20, max_codepoint=0x7E),
    st.sampled_from("\x00\x1f\x7f\x80é \U0001f600"),
)

# Invalid input is logged on every exec, which is slow and floods stderr
logging.disable(logging.CRITICAL)


def _limited_members(headers: list[str]) -> list[str]:
    """Returns the list-members of the given headers that are within the limits, valid or not."""
    members: list[str] = []
    length = 0
    for header in headers:
        for member in header.split(","):
            member = member.strip(_OWS)
            if not member or not member.isascii() or len(member) > _MAX_PAIR_LENGTH:
                continue
            length += len(member) + (1 if members else 0)
            if len(members) == _MAX_PAIRS or length > _MAX_LENGTH:
                return members
            members.append(member)
    return members


def _parse_member(member: str) -> tuple[str, str] | None:
    """Returns the key and the value of a list-member, or none if it is invalid."""
    try:
        key, *rest = _GRAMMAR.parse(member).children
    except UnexpectedInput:
        return None
    value = next((token for token in rest if isinstance(token, Token) and token.type == "VALUE"), "")
    return str(key), str(value)


def _expected_entries(headers: list[str]) -> dict[str, str]:
    """Returns the entries a baggage made of the given headers holds."""
    entries = {}
    for member in _limited_members(headers):
        parsed = _parse_member(member)
        if parsed is not None:
            key, value = parsed
            entries[key] = unquote(value)
    return entries


def _values() -> st.SearchStrategy[str]:
    """Generates values made of baggage-octets, mixed with percent-encoded characters."""
    octet = st.from_regex(_GRAMMAR.get_terminal("VALUE").pattern.to_regexp(), fullmatch=True)
    encoded = st.characters(codec="utf-8").map(lambda char: quote(char, safe=""))
    return st.lists(st.one_of(octet, encoded, st.sampled_from(_PERCENT_ESCAPES)), min_size=1, max_size=8).map("".join)


@st.composite
def _valid_baggage(draw: st.DrawFn) -> str:
    """Generates valid baggage header values within the limits, with OWS and empty list-members."""
    members = draw(st.lists(from_lark(_GRAMMAR, explicit={"VALUE": _values()}), max_size=8))
    ows = st.text(alphabet=_OWS, max_size=2)
    separator = st.builds(
        lambda before, commas, after: before + commas + after, ows, st.sampled_from([",", ",,", ", ,"]), ows
    )
    baggage_string = draw(ows)
    for index, member in enumerate(members):
        baggage_string += (draw(separator) if index else "") + member
    baggage_string += draw(ows)
    assume(len(baggage_string) <= _MAX_LENGTH and all(len(member) <= _MAX_PAIR_LENGTH for member in members))
    return baggage_string


def _insert_percent_escape(draw: st.DrawFn, baggage_string: str) -> str:
    index = draw(st.integers(0, len(baggage_string)))
    return baggage_string[:index] + draw(st.sampled_from(_PERCENT_ESCAPES)) + baggage_string[index:]


def _exceed_pair_length(draw: st.DrawFn, baggage_string: str) -> str:
    # "k=" and the value make a list-member of 4095 to 4100 characters
    return f"{baggage_string},k={'v' * draw(st.integers(_MAX_PAIR_LENGTH - 3, _MAX_PAIR_LENGTH + 2))}"


def _exceed_pair_count(draw: st.DrawFn, baggage_string: str) -> str:
    extra = draw(st.integers(_MAX_PAIRS - 2, _MAX_PAIRS + 4))
    return ",".join([baggage_string, *(f"k{index}=v" for index in range(extra))])


def _exceed_total_length(draw: st.DrawFn, baggage_string: str) -> str:
    target = draw(st.integers(_MAX_LENGTH - 8, _MAX_LENGTH + 8))
    members = [baggage_string]
    while (length := len(",".join(members))) < target:
        filler = min(_MAX_PAIR_LENGTH - 8, max(0, target - length - 8))
        members.append(f"p{len(members)}={'x' * filler}")
    return ",".join(members)


def _structural_member(draw: st.DrawFn, key: str, value: str) -> str:
    return draw(
        st.sampled_from(
            [
                key,
                f"={value}",
                f"{key} = {value} ; p = 1 ; q",
                f"{key} x={value}",
                f"{key}={value} x",
                f'{key}="{value}"',
                f"{key}={value};",
                f"{key}={value};;p",
                f"{key}={value};={value}",
                f"{key}={value};p q",
                f"{key}={value};p=v w",
            ]
        )
    )


def _duplicate_member(draw: st.DrawFn, key: str, value: str) -> str:
    return f"{key}={value},{key}={draw(st.sampled_from([value, 'other']))}"


def _member_mutation(mutate_member: Callable[[st.DrawFn, str, str], str]) -> Mutation:
    """Wraps a mutation of a single list member into a mutation of the whole header."""

    def mutation(draw: st.DrawFn, baggage_string: str) -> str:
        spans = [match.span() for match in re.finditer(r"[^,]*[^, \t][^,]*", baggage_string)]
        assume(spans)
        start, end = draw(st.sampled_from(spans))
        key, _, value = baggage_string[start:end].strip(_OWS).partition("=")
        return baggage_string[:start] + mutate_member(draw, key.strip(_OWS), value.strip(_OWS)) + baggage_string[end:]

    return mutation


_MUTATIONS: list[Mutation] = [
    *char_mutations(_INVALID_CHARS),
    _insert_percent_escape,
    _exceed_pair_length,
    _exceed_pair_count,
    _exceed_total_length,
    _member_mutation(_structural_member),
    _member_mutation(_duplicate_member),
]


@st.composite
def _mutated_baggage(draw: st.DrawFn) -> str:
    """Generates valid baggage header values with a mutation that most likely makes a list-member invalid."""
    mutation = draw(st.sampled_from(_MUTATIONS))
    return mutation(draw, draw(_valid_baggage()))


def _random_baggage() -> st.SearchStrategy[str]:
    """Generates random strings made mostly of characters that are significant in a baggage."""
    return st.text(alphabet=_RANDOM_ALPHABET, max_size=512)


def _baggage_headers() -> st.SearchStrategy[list[str]]:
    """Generates the baggage header values of a request, valid or not."""
    return st.one_of(_valid_baggage(), _mutated_baggage(), _random_baggage()).flatmap(split_headers)


def _entries_in(ctx: Context) -> dict[str, str]:
    return {key: str(value) for key, value in baggage.get_all(ctx).items()}


@settings(database=None, deadline=None, suppress_health_check=list(HealthCheck))
@given(_baggage_headers())
def test_baggage(headers: list[str]) -> None:
    ctx = _PROPAGATOR.extract({"baggage": headers}, context=Context())
    entries = _entries_in(ctx)

    expected = _expected_entries(headers)
    if entries != expected:
        raise AssertionError(f"extracted {entries!r} from {headers!r}, grammar expected {expected!r}")

    carrier: dict[str, str] = {}
    _PROPAGATOR.inject(carrier, ctx)
    injected = carrier.get("baggage")
    if injected is not None and len(injected) > _MAX_LENGTH:
        raise AssertionError(f"injected baggage of {len(injected)} characters from {headers!r}")

    reextracted = _entries_in(_PROPAGATOR.extract({key: [value] for key, value in carrier.items()}, context=Context()))
    # Percent-encoding can push list-members over the limits, which drops them
    encoded = [f"{key}={quote(value, safe='')}" for key, value in entries.items()]
    within_limits = all(len(member) <= _MAX_PAIR_LENGTH for member in encoded) and len(",".join(encoded)) <= _MAX_LENGTH
    round_trips = reextracted == entries if within_limits else reextracted.items() <= entries.items()
    if not round_trips:
        raise AssertionError(f"injected {injected!r} re-extracted as {reextracted!r}, expected {entries!r}")


def main() -> None:
    atheris.Setup(sys.argv, atheris.instrument_func(test_baggage.hypothesis.fuzz_one_input))
    atheris.Fuzz()


if __name__ == "__main__":
    main()

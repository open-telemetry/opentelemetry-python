"""Fuzz W3C tracestate handling in TraceContextTextMapPropagator.

Headers are generated by Hypothesis from ``fuzz/grammars/tracestate.lark``, a
translation of the W3C Trace Context ABNF
(https://www.w3.org/TR/trace-context/#tracestate-header-field-values).
"""

import logging
import sys
from collections.abc import Callable
from pathlib import Path

import atheris
from _strategies import Mutation, char_mutations, split_headers
from hypothesis import HealthCheck, assume, given, settings
from hypothesis import strategies as st
from hypothesis.extra.lark import from_lark
from lark import Lark, Token, UnexpectedInput

with atheris.instrument_imports():
    from opentelemetry import trace
    from opentelemetry.context.context import Context
    from opentelemetry.trace.propagation.tracecontext import (
        TraceContextTextMapPropagator,
    )
    from opentelemetry.trace.span import TraceState

_PROPAGATOR = TraceContextTextMapPropagator()
_TRACEPARENT = "00-0af7651916cd43dd8448eb211c80319c-b7ad6b7169203331-01"
_GRAMMAR = Lark.open(str(Path(__file__).parent.parent / "grammars" / "tracestate.lark"), parser="lalr")

_MAX_KEYS = 32
_MAX_LENGTH = 8192

_KEY_CHARS = "abcdefghijklmnopqrstuvwxyz0123456789_-*/"
# Characters that are invalid in a key, a value, or both
_INVALID_CHARS = "AZ,= \t\x00\x1f\x7f\x80é \U0001f600"
_RANDOM_ALPHABET = st.one_of(
    st.sampled_from(",=@ \t"),
    st.characters(min_codepoint=0x20, max_codepoint=0x7E),
    st.sampled_from("\x00\x1f\x7f\x80é \U0001f600"),
)

# Invalid input is logged on every exec, which is slow and floods stderr
logging.disable(logging.CRITICAL)


def _member_tokens(tracestate: str) -> list[Token]:
    return _GRAMMAR.parse(tracestate).children


def _parse_member(member: str) -> tuple[str, str]:
    key, value = member.split("=", 1)
    return key, value


def _expected_entries(headers: list[str]) -> list[tuple[str, str]]:
    """Returns the entries a tracestate made of the given headers holds, or none if it is invalid."""
    combined = ",".join(headers)
    if len(combined) > _MAX_LENGTH:
        return []
    try:
        entries = [_parse_member(token) for token in _member_tokens(combined)]
    except UnexpectedInput:
        return []
    if len({key for key, _ in entries}) != len(entries):
        return []
    return entries


@st.composite
def _valid_tracestates(draw: st.DrawFn) -> str:
    """Generates valid tracestate header values within the limits."""
    tracestate = draw(from_lark(_GRAMMAR))
    keys = [_parse_member(token)[0] for token in _member_tokens(tracestate)]
    assume(len(set(keys)) == len(keys) and len(tracestate) <= _MAX_LENGTH)
    return tracestate


def _exceed_total_length(draw: st.DrawFn, tracestate: str) -> str:
    # empty list members pad the header without changing its entries
    padding = draw(st.integers(_MAX_LENGTH + 1 - len(tracestate), _MAX_LENGTH + 64 - len(tracestate)))
    return tracestate + "," * padding


def _exceed_key_count(draw: st.DrawFn, tracestate: str) -> str:
    extra = draw(st.integers(_MAX_KEYS + 1, _MAX_KEYS + 4))
    return ",".join([tracestate, *(f"k{index}=v" for index in range(extra))])


def _structural_member(draw: st.DrawFn, key: str, value: str) -> str:
    return draw(
        st.sampled_from(
            [
                f"{key}{value}",
                f"={value}",
                f"{key}=",
                f"0{key}={value}",
                f"{key}@@x={value}",
                f"{key} ={value}",
                f"{key},{value}",
                f"{key}={value}={value}",
            ]
        )
    )


def _over_limit_member(draw: st.DrawFn, key: str, value: str) -> str:
    pad = draw(st.sampled_from(_KEY_CHARS))
    if "@" in key:
        tenant_id, system_id = key.split("@", 1)
        long_key = draw(st.sampled_from([f"{tenant_id:{pad}<242}@{system_id}", f"{tenant_id}@{system_id:{pad}<15}"]))
    else:
        long_key = f"{key:{pad}<257}"
    return draw(st.sampled_from([f"{long_key}={value}", f"{key}={value:x>257}"]))


def _duplicate_member(draw: st.DrawFn, key: str, value: str) -> str:
    return f"{key}={value},{key}={draw(st.sampled_from([value, 'other']))}"


def _member_mutation(mutate_member: Callable[[st.DrawFn, str, str], str]) -> Mutation:
    """Wraps a mutation of a single list member into a mutation of the whole header."""

    def mutation(draw: st.DrawFn, tracestate: str) -> str:
        tokens = _member_tokens(tracestate)
        assume(tokens)
        token = draw(st.sampled_from(tokens))
        member = mutate_member(draw, *_parse_member(token))
        return tracestate[: token.start_pos] + member + tracestate[token.end_pos :]

    return mutation


_MUTATIONS: list[Mutation] = [
    *char_mutations(_INVALID_CHARS),
    _exceed_total_length,
    _exceed_key_count,
    _member_mutation(_structural_member),
    _member_mutation(_over_limit_member),
    _member_mutation(_duplicate_member),
]


@st.composite
def _mutated_tracestates(draw: st.DrawFn) -> str:
    """Generates valid tracestate header values with a mutation that most likely makes them invalid."""
    mutation = draw(st.sampled_from(_MUTATIONS))
    return mutation(draw, draw(_valid_tracestates()))


def _random_tracestates() -> st.SearchStrategy[str]:
    """Generates random strings made mostly of characters that are significant in a tracestate."""
    return st.text(alphabet=_RANDOM_ALPHABET, max_size=512)


def _tracestate_headers() -> st.SearchStrategy[list[str]]:
    """Generates the tracestate header values of a request, valid or not."""
    return st.one_of(_valid_tracestates(), _mutated_tracestates(), _random_tracestates()).flatmap(split_headers)


def _trace_state_in(ctx: Context) -> TraceState:
    span_context = trace.get_current_span(ctx).get_span_context()
    if not span_context.is_valid:
        raise AssertionError("valid traceparent was rejected")
    return span_context.trace_state


@settings(database=None, deadline=None, suppress_health_check=list(HealthCheck))
@given(_tracestate_headers())
def test_tracestate(headers: list[str]) -> None:
    ctx = _PROPAGATOR.extract({"traceparent": [_TRACEPARENT], "tracestate": headers})
    entries = list(_trace_state_in(ctx).items())

    expected = _expected_entries(headers)
    if entries != expected:
        raise AssertionError(f"extracted {entries!r} from {headers!r}, grammar expected {expected!r}")

    carrier: dict[str, str] = {}
    _PROPAGATOR.inject(carrier, ctx)
    injected = carrier.get("tracestate")
    if injected is not None and len(injected) > _MAX_LENGTH:
        raise AssertionError(f"injected tracestate of {len(injected)} characters from {headers!r}")

    reextracted = _trace_state_in(_PROPAGATOR.extract({key: [value] for key, value in carrier.items()}))
    if list(reextracted.items()) != entries:
        raise AssertionError(f"injected {injected!r} re-extracted as {reextracted!r}, expected {entries!r}")


def main() -> None:
    atheris.Setup(sys.argv, atheris.instrument_func(test_tracestate.hypothesis.fuzz_one_input))
    atheris.Fuzz()


if __name__ == "__main__":
    main()
